def contract_stub_body(contract_cls: type, emitter: _Emitter | None = None) -> list[str]:
    """
    Stub lines for one Contract's class body.

    Args:
        contract_cls: A compiled Contract subclass.
        emitter: Collector for the imports the annotations need. A throwaway
            one is used when omitted, which is fine for previewing a single
            class but loses the imports the stub would need.

    Returns:
        Indented class-body lines, always at least ``["    ..."]`` so the
        result is syntactically valid even for a Contract with no fields.

    Examples:
        >>> from aquilia.contracts import Contract, TextFacet
        >>> class UserContract(Contract):
        ...     email = TextFacet()
        >>> contract_stub_body(UserContract)
        ['    email: str']
    """
    sink = emitter if emitter is not None else _Emitter()
    body: list[str] = []

    for name, facet in getattr(contract_cls, "_all_facets", {}).items():
        annotation = _facet_annotation(facet, contract_cls, name, sink)
        body.append(f"    {name}: {sink.annotate(annotation)}")

    body.extend(_method_stubs(contract_cls, sink))
    return body or ["    ..."]


def _facet_annotation(facet: Any, owner: type, name: str, sink: _Emitter) -> str:
    """
    Annotation for one facet's validated value, widened for nullability.

    A facet that accepts ``None`` — explicitly via ``allow_null``, or
    implicitly by defaulting to it — must be annotated optional. Omitting that
    is worse than emitting no stub at all: it tells the type checker a value
    can never be ``None`` at exactly the points a caller needs a guard.
    """
    try:
        annotation = facet.python_type()
    except Exception as exc:  # pragma: no cover - defensive
        sink.degraded.append(f"{owner.__name__}.{name}: python_type() raised {type(exc).__name__}")
        return "Any"

    if annotation == "Any":
        sink.degraded.append(f"{owner.__name__}.{name}: {type(facet).__name__} declares no Python type")
        return "Any"

    if getattr(facet, "allow_null", False) or _defaults_to_none(facet):
        return f"{annotation} | None"
    return annotation


def _defaults_to_none(facet: Any) -> bool:
    """True if the facet's declared default is ``None``."""
    from aquilia.contracts.facets import UNSET

    default = getattr(facet, "default", UNSET)
    return default is None


def _method_stubs(cls: type, sink: _Emitter) -> list[str]:
    """
    Signatures for the public methods a class declares itself.

    Inherited methods are left out: the type checker reads the base class from
    its own source (or its own stub) and already knows them. Only what this
    class adds would be lost when the stub shadows the module.
    """
    lines: list[str] = []
    for name, member in vars(cls).items():
        if name.startswith("_") or not inspect.isfunction(member):
            continue
        lines.append(f"    {_signature(member, name, cls.__name__, sink)}")
    return lines


def _signature(fn: Any, name: str, owner: str, sink: _Emitter) -> str:
    """Render one ``def`` line, degrading to ``*args, **kwargs`` if unreadable."""
    try:
        rendered = str(_unquoted(inspect.signature(fn)))
    except (TypeError, ValueError) as exc:
        sink.degraded.append(f"{owner}.{name}: signature unavailable ({type(exc).__name__})")
        return f"def {name}(*args: Any, **kwargs: Any) -> Any: ..."

    sink.imports.update(_imports_for(rendered))
    prefix = "async " if inspect.iscoroutinefunction(fn) else ""
    return f"{prefix}def {name}{rendered}: ..."


class _Raw:
    """Renders its text verbatim where ``inspect`` would apply ``repr``."""

    __slots__ = ("text",)

    def __init__(self, text: str):
        self.text = text

    def __repr__(self) -> str:
        return self.text


def _unquoted(sig: inspect.Signature) -> inspect.Signature:
    """
    Strip the quoting ``from __future__ import annotations`` leaves behind.

    Under PEP 563 every annotation reaches ``inspect`` as a string, so
    ``str(signature)`` renders ``x: int`` as ``x: 'int'``. Both forms are legal
    in a stub, but a file that mixes them looks like a generator defect to
    whoever reviews the diff.
    """

    def unwrap(value: Any) -> Any:
        return _Raw(value) if isinstance(value, str) else value

    params = [p.replace(annotation=unwrap(p.annotation)) for p in sig.parameters.values()]
    return sig.replace(parameters=params, return_annotation=unwrap(sig.return_annotation))


