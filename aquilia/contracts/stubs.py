def generate_module_stub(module: ModuleType) -> StubReport:
    """
    Build the ``.pyi`` stub for an already-imported module.

    The module must be imported first: facets are compiled by ``ContractMeta``
    during class-body evaluation, so an unimported module has nothing to
    inspect. Importing it is the caller's job, which keeps this function free
    of import side effects.

    Args:
        module: The imported module.

    Returns:
        A :class:`StubReport` carrying the stub text and everything that had to
        be degraded to ``Any``.

    Raises:
        StubGenerationFault: If the module has no ``__file__`` (a namespace
            package or a synthetic module), so there is nowhere a stub could
            sit and no source to read imports from.
    """
    from aquilia.contracts.core import Contract
    from aquilia.contracts.exceptions import StubGenerationFault

    source_file = getattr(module, "__file__", None)
    if not source_file:
        raise StubGenerationFault(
            f"Module '{module.__name__}' has no source file, so a stub has no location to occupy."
        )

    path = Path(source_file).with_suffix(".pyi")
    sink = _Emitter()
    contracts: list[str] = []

    for name, obj in vars(module).items():
        if name.startswith("_") or getattr(obj, "__module__", None) != module.__name__:
            continue
        if isinstance(obj, type) and issubclass(obj, Contract):
            contracts.append(name)
            sink.lines.extend(_contract_class(obj, module, sink))
        elif isinstance(obj, type):
            sink.lines.extend(_plain_class(obj, sink))
        elif inspect.isfunction(obj):
            sink.lines.append(_signature(obj, name, module.__name__, sink))
            sink.lines.append("")
        else:
            sink.lines.append(f"{name}: Any")
            sink.degraded.append(f"{name}: module-level value emitted as Any")

    text = _assemble(module, source_file, sink)
    return StubReport(
        module=module.__name__,
        source=text,
        path=path,
        contracts=tuple(contracts),
        degraded=tuple(sink.degraded),
    )


def _contract_class(cls: type, module: ModuleType, sink: _Emitter) -> list[str]:
    """Emit one Contract class declaration with its facet-derived fields."""
    bases = ", ".join(_base_name(base, module, sink) for base in cls.__bases__) or "object"
    return [f"class {cls.__name__}({bases}):", *contract_stub_body(cls, sink), ""]


def _plain_class(cls: type, sink: _Emitter) -> list[str]:
    """
    Emit a non-Contract class the module defines.

    Enums keep their members — a stub that drops them turns every
    ``Colour.RED`` in the codebase into an attribute error. Everything else
    gets its public method signatures, which is what callers type against.
    """
    bases = ", ".join(_qualified(base, sink) for base in cls.__bases__) or "object"
    body: list[str] = []

    if isinstance(cls, type) and issubclass(cls, enum.Enum):
        # ``NAME: Colour`` declares an *annotation*, which the typing spec
        # reads as a non-member attribute — mypy then sees an enum with zero
        # members. Assigning the value is what marks it as a member; ``...``
        # stands in when the value has no literal form.
        body.extend(f"    {member.name} = {_literal_or_ellipsis(member.value)}" for member in cls)
    body.extend(_method_stubs(cls, sink))

    return [f"class {cls.__name__}({bases}):", *(body or ["    ..."]), ""]


def _literal_or_ellipsis(value: Any) -> str:
    """Render an enum member's value, or ``...`` if it has no literal form."""
    if value is None or isinstance(value, (str, int, float, bool, bytes)):
        return repr(value)
    return "..."


def _base_name(base: type, module: ModuleType, sink: _Emitter) -> str:
    """Reference a base class, unqualified when it lives in the same module."""
    if getattr(base, "__module__", None) == module.__name__:
        return base.__name__
    return _qualified(base, sink)


def _qualified(obj: type, sink: _Emitter) -> str:
    """Fully-qualified name of a class, recording the import it needs."""
    mod = getattr(obj, "__module__", "")
    name = getattr(obj, "__qualname__", getattr(obj, "__name__", "Any"))
    if not mod or mod == "builtins":
        return name
    if "<locals>" in name:
        sink.degraded.append(f"{name}: locally-defined class emitted as Any")
        return "Any"
    sink.imports.add(mod)
    return f"{mod}.{name}"


def _assemble(module: ModuleType, source_file: str, sink: _Emitter) -> str:
    """Join the header, imports, and emitted declarations into stub text."""
    parts = [_HEADER, "\n", _BASE_IMPORTS]

    replayed = _source_imports(source_file)
    if replayed:
        parts.append("".join(f"{line}\n" for line in replayed))

    # A module imported by the source and also required by an annotation would
    # otherwise be emitted twice; harmless to Python, but a stub with duplicate
    # imports reads as a generator bug to whoever reviews the diff.
    already = set(replayed)
    own = getattr(module, "__name__", "")
    extra = sorted(f"import {name}" for name in sink.imports if name != own)
    extra = [line for line in extra if line not in already]
    if extra:
        parts.append("".join(f"{line}\n" for line in extra))

    parts.append("\n")
    parts.append("\n".join(sink.lines).rstrip())
    parts.append("\n")
    return "".join(parts)


def _source_imports(source_file: str) -> list[str]:
    """
    Replay the module's own import statements into the stub.

    Method signatures are rendered from the runtime objects, and under ``from
    __future__ import annotations`` those come back as the source text the
    module wrote — bare names that only resolve against the module's own
    imports. Replaying them is what keeps those signatures meaningful instead
    of collapsing to ``Any``.

    Returns an empty list if the source cannot be read or parsed: a stub
    missing some imports is still useful, and refusing to generate one because
    a file could not be re-read is not.
    """
    try:
        tree = ast.parse(Path(source_file).read_text(encoding="utf-8"))
    except (OSError, SyntaxError, ValueError):
        return []

    return [
        ast.unparse(node)
        for node in tree.body
        if isinstance(node, (ast.Import, ast.ImportFrom)) and getattr(node, "module", None) != "__future__"
    ]


def write_module_stub(module: ModuleType, *, dry_run: bool = False) -> StubReport:
    """
    Generate a module's stub and write it beside the module's source.

    Args:
        module: The imported module to stub.
        dry_run: Build the report without touching the filesystem. Use with
            :attr:`StubReport.is_current` to fail CI on a stale stub.

    Returns:
        The :class:`StubReport`, whose ``path`` names the file written.
    """
    report = generate_module_stub(module)
    if not dry_run:
        report.path.write_text(report.source, encoding="utf-8")
    return report
