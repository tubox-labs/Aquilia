"""
Aquilia Contract stub generation -- ``.pyi`` emission for static type checkers.

A Contract resolves its fields at class-body evaluation time, and an instance
exposes them through ``__getattr__``. Both are invisible to a static analyser:
``mypy`` and ``pyright`` see ``UserContract(...).email`` as ``Any`` at best,
and as an attribute error under ``--strict`` at worst.

This module closes that gap without a bespoke type-checker plugin. It walks a
module's Contract classes at runtime — after ``ContractMeta`` has compiled
them, so every facet is resolved — and emits a ``.pyi`` stub declaring each
field with the Python type its facet *produces*. ``IntFacet`` accepts the
string ``"42"`` on the wire but yields ``int``, and the stub says ``int``.

A ``.pyi`` is a portable artifact: every type checker consumes it, no plugin
needs installing, and it is checked into the repository like any other
generated file.

Usage::

    aq contracts stubs myapp.contracts            # write myapp/contracts.pyi
    aq contracts stubs myapp.contracts --check     # fail if out of date (CI)

Limitations:
    A ``.pyi`` *replaces* its module for the type checker — it does not
    augment it. This generator therefore reproduces the whole module surface,
    not only its Contracts: import statements are replayed from the source
    AST, and module-level classes, functions, and constants are emitted with
    their runtime signatures. Anything it cannot render faithfully is emitted
    as ``Any`` and listed in :attr:`StubReport.degraded`, so a lost annotation
    is reported rather than silently weakening the module's types.
"""

from __future__ import annotations

import ast
import enum
import inspect
import sys
from dataclasses import dataclass, field
from pathlib import Path
from types import ModuleType
from typing import Any

__all__ = [
    "StubReport",
    "contract_stub_body",
    "generate_module_stub",
    "write_module_stub",
]

_HEADER = (
    "# Generated by `aq contracts stubs`. Do not edit by hand.\n"
    "# Regenerate after changing the Contract declarations in the paired module.\n"
)

#: Emitted unconditionally: facet-derived annotations use ``Any`` as their
#: fallback and ``Literal`` for choice/constant facets.
_BASE_IMPORTS = "from typing import Any, Literal\n"


@dataclass(frozen=True, slots=True)
class StubReport:
    """
    Outcome of generating one module's stub.

    Attributes:
        module: Dotted name of the module the stub describes.
        source: The ``.pyi`` text.
        path: Where the stub belongs, alongside the module's ``.py``.
        contracts: Names of the Contract classes that were stubbed.
        degraded: Members whose types could not be rendered faithfully and were
            emitted as ``Any``, each as ``"name: reason"``. A non-empty list is
            not an error, but it names exactly what the stub does not know.
    """

    module: str
    source: str
    path: Path
    contracts: tuple[str, ...] = ()
    degraded: tuple[str, ...] = ()

    @property
    def is_current(self) -> bool:
        """True if the on-disk stub already matches :attr:`source`."""
        try:
            return self.path.read_text(encoding="utf-8") == self.source
        except FileNotFoundError:
            return False


@dataclass(slots=True)
class _Emitter:
    """Accumulates stub lines plus the imports and degradations they imply."""

    lines: list[str] = field(default_factory=list)
    imports: set[str] = field(default_factory=set)
    degraded: list[str] = field(default_factory=list)

    def annotate(self, text: str) -> str:
        """Record the imports an annotation needs and return it unchanged."""
        self.imports.update(_imports_for(text))
        return text


# ---------------------------------------------------------------------------
# Import resolution
# ---------------------------------------------------------------------------


def _imports_for(annotation: str) -> set[str]:
    """
    Modules that must be imported for ``annotation`` to resolve in a stub.

    Facets fully qualify the types they produce (``decimal.Decimal``,
    ``myapp.enums.Colour``), so the import is the longest dotted prefix that is
    a real module. The owning module is already imported at generation time —
    that is what makes the facets inspectable — so ``sys.modules`` answers
    exactly, with no filesystem probing and no risk of importing something new
    as a side effect of generating a stub.

    Args:
        annotation: Annotation source text, e.g. ``"list[decimal.Decimal]"``.

    Returns:
        Module names to import.
    """
    found: set[str] = set()
    for dotted in _dotted_names(annotation):
        parts = dotted.split(".")
        for cut in range(len(parts) - 1, 0, -1):
            candidate = ".".join(parts[:cut])
            if candidate in sys.modules:
                found.add(candidate)
                break
    return found


def _dotted_names(text: str) -> set[str]:
    """Extract dotted identifiers from annotation source text."""
    names: set[str] = set()
    current: list[str] = []
    for char in text:
        if char.isalnum() or char in "._":
            current.append(char)
        else:
            if current:
                names.add("".join(current))
            current = []
    if current:
        names.add("".join(current))
    return {n for n in names if "." in n and not n[0].isdigit()}


